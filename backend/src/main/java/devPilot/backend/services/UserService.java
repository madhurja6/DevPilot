package devPilot.backend.services;

import java.util.Map;
import java.util.UUID;

import org.springframework.security.crypto.encrypt.TextEncryptor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import devPilot.backend.entity.User;
import devPilot.backend.exceptions.NotFoundException;
import devPilot.backend.repository.UserRepository;
import lombok.RequiredArgsConstructor;

@Service
@RequiredArgsConstructor
public class UserService {

    private final UserRepository userRepository;
    private final TextEncryptor textEncryptor;

    @Transactional
    public User upsertFromGithub(
            Map<String, Object> attributes,
            String accessToken,
            String scopes) {

        // Get and validate GitHub ID
        Long githubId = toLong(attributes.get("id"));

        // Get and validate GitHub username
        Object loginValue = attributes.get("login");

        if (loginValue == null
                || String.valueOf(loginValue).isBlank()) {
            throw new IllegalArgumentException(
                    "GitHub username is missing");
        }

        String login = String.valueOf(loginValue);

        // Get display name; use username if name is unavailable
        String name = attributes.get("name") != null
                && !String.valueOf(attributes.get("name")).isBlank()
                        ? String.valueOf(attributes.get("name"))
                        : login;

        // Get avatar URL
        String avatarUrl = attributes.get("avatar_url") != null
                ? String.valueOf(attributes.get("avatar_url"))
                : null;

        // Validate access token
        if (accessToken == null || accessToken.isBlank()) {
            throw new IllegalArgumentException(
                    "GitHub access token is missing");
        }

        // Encrypt access token before saving
        String encryptedToken = textEncryptor.encrypt(accessToken);

        // Find existing user or create a new user
        User user = userRepository.findByGithubId(githubId)
                .orElseGet(User::new);

        // Update GitHub user information
        user.setGithubId(githubId);
        user.setGithubUsername(login);
        user.setDisplayName(name);
        user.setAvatarUrl(avatarUrl);
        user.setAccessToken(encryptedToken);
        user.setTokenScopes(scopes);

        // Save the user
        // UUID and createdAt are generated by User.java @PrePersist
        return userRepository.save(user);
    }

    @Transactional(readOnly = true)
    public User requiredById(UUID id) {
        return userRepository.findById(id)
                .orElseThrow(() -> new NotFoundException("User not found"));
    }

    public String decryptAccessToken(User user) {
        return textEncryptor.decrypt(user.getAccessToken());
    }

    private static Long toLong(Object value) {
        if (value == null) {
            throw new IllegalArgumentException(
                    "GitHub ID is missing");
        }

        if (value instanceof Number number) {
            return number.longValue();
        }

        try {
            return Long.parseLong(String.valueOf(value));
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException(
                    "Invalid GitHub ID", e);
        }
    }
}